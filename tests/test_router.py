import pytest

from app.router import needs_reasoning


@pytest.mark.parametrize("text", [
    "ช่วยคำนวณดอกเบี้ยเงินกู้ 500000 บาท 5 ปีให้หน่อย",
    "125 คูณ 48 ได้เท่าไหร่",
    "สามบวกห้าเท่ากับเท่าไหร่",
    "12 + 7 * 3",
    "ถ้าลดราคา 15 เปอร์เซ็นต์ จาก 2400 จะเหลือกี่บาท",
    "ช่วยวางแผนเที่ยวเชียงใหม่สามวัน",
    "จัดตารางอ่านหนังสือสอบให้หน่อย",
    "เปรียบเทียบไอโฟนกับแอนดรอยด์ให้ฟังหน่อย",
    "รถไฟฟ้ากับรถเมล์ อันไหนดีกว่ากัน",
    "ข้อดีข้อเสียของการเช่าบ้านกับซื้อบ้าน",
    "compare python vs rust for this project",
    "how much is 17% of 2300",
])
def test_reasoning_turns(text):
    assert needs_reasoning(text)


@pytest.mark.parametrize("text", [
    "สวัสดีค่ะ",
    "วันนี้อากาศเป็นยังไงบ้าง",
    "ฉันใส่เสื้อสีอะไรอยู่",
    "เปิดแผนที่ไปสยามหน่อย",
    "แผนกบัญชีอยู่ชั้นไหน",
    "พยายามคิดบวกไว้นะ",
    "ช่วยลบข้อความนี้ทิ้ง",
    "เล่าเรื่องตลกให้ฟังหน่อย",
    "",
])
def test_fast_turns(text):
    assert not needs_reasoning(text)
